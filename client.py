# client.py
# Этот файл отвечает за общение с пользователем:
#   - спрашивает имя
#   - читает команды из консоли
#   - разбирает команду «войти НОМЕР [ИМЯ]»
#   - передаёт готовое сообщение в send.py и получает ответ сервера

# Импортируем функцию отправки из соседнего файла send.py
from send import send_message


def main():
    # Спрашиваем имя игрока. strip() убирает лишние пробелы по краям.
    name = input("Имя: ").strip()
    # Если имя пустое — играть без имени нельзя, выходим.
    if not name:
        return

    # room_id = None означает «мы пока ни в одной комнате».
    # Как только игрок введёт «войти НОМЕР», сюда попадёт номер комнаты.
    room_id = None

    # Подсказка для игрока, что делать дальше.
    print("Введите «войти НОМЕР» для входа в комнату.")

    # Бесконечный цикл: читаем строки, пока игрок не нажмёт Ctrl+C / Ctrl+D.
    while True:
        # Читаем строку. Если игрок закрыл ввод — аккуратно выходим.
        try:
            text = input()
        except (EOFError, KeyboardInterrupt):
            return

        # Пустую строку (или строку из пробелов) просто пропускаем.
        if not text.strip():
            continue

        # Разбираем введённый текст.
        # maxsplit=2 значит: делим максимум на 3 части —
        #   ["войти", "НОМЕР", "ИМЯ (если есть)"]
        parts = text.split(maxsplit=2)

        # Проверяем: это команда входа?
        #   - частей минимум 2 (есть «войти» и номер)
        #   - первое слово (без учёта регистра) — «войти»
        if len(parts) >= 2 and parts[0].lower() == "войти":
            # Запоминаем номер комнаты
            room_id = parts[1]
            if len(parts) == 3:
                # Игрок сам указал имя в команде — используем именно его
                name = parts[2]
            else:
                # Имя не указано — подставляем то, что ввели в самом начале
                text = f"войти {room_id} {name}"

        # Пока не вошли в комнату — писать некуда, просим войти.
        if room_id is None:
            print("Сначала войдите: «войти НОМЕР».")
            continue

        # Всё готово: отдаём сообщение в модуль отправки.
        # send_message возвращает ответ сервера (dict) или None при ошибке.
        response = send_message(room_id, name, text)

        # Если сервер вернул цвет нашего танка — показываем его игроку.
        if isinstance(response, dict):
            color = response.get("your_color")
            if color:
                print(f"Ваш цвет танка: {color}")


# Точка входа: этот блок выполняется, только если запустить файл напрямую.
if __name__ == "__main__":
    main()